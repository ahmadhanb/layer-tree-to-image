    def deleteRow(self): # called when delete button is triggerd on selected row/s
        if self.layerTable.selectionModel().hasSelection():
            indexes =[QPersistentModelIndex(index) for index in self.layerTable.selectionModel().selectedRows()]
            for index in indexes:
                print('Deleting row %d...' % index.row())
                self.layerTable.removeRow(index.row())
                
