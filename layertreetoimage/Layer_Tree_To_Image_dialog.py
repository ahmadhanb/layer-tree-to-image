    def all_check(self):
        layerTable = self.layerTable
        while True:
            if (self.allLyrRadBtn.isChecked() or self.allLyrRadBtn_2.isChecked()):
                if layerTable.rowCount() == 0:
                    iface.messageBar().pushMessage("Warning", 'No layers loaded, \
                                    please load layers, then select.', level=Qgis.Warning) 
                break          

        if self.allLyrRadBtn.isChecked():
            if layerTable.rowCount() > 0:
                iface.actionHideAllLayers().trigger()

        if self.allLyrRadBtn_2.isChecked():
            if layerTable.rowCount() > 0:
                iface.actionShowAllLayers().trigger()
                
    def select_check(self):
        layerTable = self.layerTable
        while True:
            if (self.selLyrRadBtn.isChecked() or self.selLyrRadBtn_2.isChecked()):
                if layerTable.rowCount() == 0:
                    iface.messageBar().pushMessage("Warning", 'No layers loaded, \
                                    please load layers, then select.', level=Qgis.Warning)

                break

        if self.selLyrRadBtn.isChecked():
            if layerTable.rowCount() > 0:
                iface.actionHideSelectedLayers().trigger()

        if self.selLyrRadBtn_2.isChecked():
            if layerTable.rowCount() > 0:
                iface.actionShowSelectedLayers().trigger()
            
    def load_layer(self):
        iface.layerTreeView().clearSelection()
        total_layer_counter = 0
        lyrs = [lyr.name() for lyr in QgsProject.instance().mapLayers().values()]
        if len(lyrs) == 0:
            iface.messageBar().pushMessage("Error", "There is no layers loaded \
                            in your project.", level=Qgis.Critical)
        for lyr in lyrs:
            total_layer_counter+=1
        
        row_nb = total_layer_counter
        col_nb = 1
        self.layerTable.setRowCount(row_nb)
        self.layerTable.setColumnCount(col_nb)
        curr_row = 0
        
        lyrs = [lyr.name() for lyr in QgsProject.instance().mapLayers().values()]
        for lyr in lyrs:
            # Add following line to only populate first column
            # of folder and sub-folder names
            col = 0
            lyr_item = QTableWidgetItem(lyr)
            # Make the folder column read-only
            lyr_item.setFlags(lyr_item.flags() ^ Qt.ItemIsEditable)
            lyr_item.setBackground(QtGui.QColor(236, 252, 229))
            self.layerTable.setItem(curr_row,col,lyr_item)
            curr_row += 1

    def selectLayer(self, layerTable, column=0):
        layerTable = self.layerTable
        if layerTable.rowCount() == 0:
            iface.messageBar().pushMessage("Error", 'No layers loaded, please load layers.', \
                            level=Qgis.Critical)
        # rowCount() This property holds the number of rows in the table
        for row in range(layerTable.rowCount()):         
            # item(row, 0) Returns the item for the given row and column if one 
            # has been set; otherwise returns nullptr.
            _item = self.layerTable.item(row, column) 
            if _item:            
                item = self.layerTable.item(row, column).text()
                print(f'row: {row}, column: {column}, item={item}')
            # enable multiSelection in the layer tree in QGIS 
            iface.layerTreeView().setSelectionMode( QAbstractItemView.MultiSelection ) 
            # loop over the laters in the layer tree to activate and select
            lyrs = [lyr for lyr in QgsProject.instance().mapLayers().values()]
            for lyr in lyrs:
                print("Layer name: {0}".format(lyr.name()))
                print("Table itme name: {0}".format(item))
                if [item] == [lyr.name()]:
                    iface.layerTreeView().setCurrentLayer(lyr)
            iface.layerTreeView().setSelectionMode(QAbstractItemView.ExtendedSelection)